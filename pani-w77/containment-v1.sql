      when 'CARNIÇAL PRETO DA MORTE' then if coalesce((p_payload->>'accept_overload')::boolean,false) then pos:=least(19,pos+1);overload:=overload+2;effect:='+1 casa e +2 sobrecarga.';else pos:=greatest(0,pos-3);effect:='Recuo 3.';end if;
      when 'ENPAP-X' then ev:=ev||jsonb_build_object('ghost_cell',least(19,pos+2));effect:='Uma casa futura foi destruída.';
      when 'DEGOLIFICADA' then if p_payload->>'card_choice'='right' then overload:=overload+1;effect:='Carta oculta direita: +1 sobrecarga.';else pos:=greatest(0,pos-1);effect:='Carta oculta esquerda: recuo 1.';end if;
      when 'MAGISTRADA' then ev:=ev||jsonb_build_object('reordered',true);effect:='Cinco casas foram reorganizadas.';
      when 'DEUS DA MORTE' then pos:=case when pos>=13 then 13 when pos>=6 then 6 else 0 end;overload:=greatest(0,overload-2);effect:='Retorno ao checkpoint; -2 sobrecarga.';
      when 'DIABO' then if coalesce((p_payload->>'accept_overload')::boolean,false) then pos:=least(19,pos+5);overload:=overload+2;effect:='+5 casas e +2 sobrecarga.';else pos:=greatest(0,pos-1);effect:='Oferta recusada: recuo 1.';end if;
      when 'ANFITRIÃO' then idx:=(array[-3,-1,1,2])[1+floor(random()*4)::int];pos:=greatest(0,least(19,pos+idx));effect:='Deslocamento do Anfitrião: '||case when idx>=0 then '+' else '' end||idx||'.';
      else null;
    end case;
    if overload>=7 then
      pos:=case when pos>=13 then 13 when pos>=6 then 6 else 0 end; overload:=4;
      st:=jsonb_set(st,'{saturation}',to_jsonb(least(8,coalesce((st->>'saturation')::int,0)+1)));
      effect:=effect||' SOBRECARGA 7/7: retorno seguro ao checkpoint.';
