create or replace function public.pani_containment_crew_state(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare c public.crew_access%rowtype; s pani_private.containment_session%rowtype;
  joined boolean := false; players jsonb := '[]'::jsonb; phase text; active_event text;
  summary jsonb := '{}'::jsonb; my_vote text; role_name text := 'spectator';
begin
  select * into c from public.crew_access
  where token_hash=encode(extensions.digest(p_token,'sha256'),'hex');
  if c.crew_id is null then raise exception 'unauthorized'; end if;
  perform pani_private.containment_tick('W77-01');
  select * into s from pani_private.containment_session where session_id='W77-01';
  select coalesce(p.joined,false) into joined from pani_private.containment_participant p
    where p.session_id='W77-01' and p.crew_id=c.crew_id;
  if joined then
    update pani_private.containment_participant set last_seen=now()
      where session_id='W77-01' and crew_id=c.crew_id;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'crew_id',p.crew_id,'display_name',ca.display_name,'module',ca.module,
    'connected',p.last_seen > now()-interval '12 seconds','last_seen',p.last_seen)
    order by ca.display_name),'[]'::jsonb) into players
  from pani_private.containment_participant p join public.crew_access ca on ca.crew_id=p.crew_id
  where p.session_id='W77-01' and p.joined;

  active_event := s.state->>'active_event'; phase := s.state#>>'{event,vote_phase}';
  if c.crew_id = s.state->>'representative_id' then role_name := 'representative'; end if;
  if c.crew_id = s.state->>'witness_id' then role_name := 'witness'; end if;
  if active_event is not null and phase is not null then
    select v.value into my_vote from pani_private.containment_vote v
      where v.session_id='W77-01' and v.event_id=active_event and v.phase_key=phase and v.crew_id=c.crew_id;
    if (active_event='death' and role_name='witness') or (active_event in ('energy','blood') and role_name='representative') then
      summary := pani_private.containment_vote_summary('W77-01',active_event,phase);
      if active_event='blood' and role_name='representative' and s.secret_state#>'{blood,fake_votes}' is not null
         and s.secret_state#>'{blood,fake_votes}' <> 'null'::jsonb then
        summary := s.secret_state#>'{blood,fake_votes}';
      end if;
    end if;
  end if;
  return jsonb_build_object(
    'session_id','W77-01','released',coalesce((s.state->>'released')::boolean,false),
    'joined',joined,'state',s.state,'revision',s.revision,'server_time',now(),
    'player',jsonb_build_object('crew_id',c.crew_id,'display_name',c.display_name,'module',c.module,'role',role_name),
    'players',players,'vote_summary',summary,'my_vote',my_vote
  );
end;
$$;

create or replace function public.pani_containment_join(p_token text, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare c public.crew_access%rowtype; s pani_private.containment_session%rowtype;
begin
  select * into c from public.crew_access where token_hash=encode(extensions.digest(p_token,'sha256'),'hex');
  if c.crew_id is null then raise exception 'unauthorized'; end if;
  select * into s from pani_private.containment_session where session_id='W77-01' for update;
  if not coalesce((s.state->>'released')::boolean,false) then raise exception 'session_closed'; end if;
  if upper(trim(coalesce(p_code,''))) is distinct from upper(trim(coalesce(s.join_code,''))) then raise exception 'invalid_session_code'; end if;
  insert into pani_private.containment_participant(session_id,crew_id,joined,joined_at,last_seen)
  values ('W77-01',c.crew_id,true,now(),now())
  on conflict (session_id,crew_id) do update set joined=true,last_seen=now(),hold_until=null;
  perform pani_private.containment_log_event('W77-01',c.display_name,'player_joined',c.crew_id);
  return public.pani_containment_crew_state(p_token);
end;
$$;

create or replace function public.pani_containment_crew_action(
  p_token text, p_action text, p_payload jsonb default '{}'::jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare c public.crew_access%rowtype; s pani_private.containment_session%rowtype;
  st jsonb; sec jsonb; ev jsonb; active_event text; phase text; value text; rep text; witness text;
  marks jsonb; mark text; cell text; idx integer; size integer; wins integer; rule_id text;
  pos integer; pulse integer; overload integer; card text; effect text; deck jsonb; deck_i integer;
  choice text; answer text; cycle integer; scene jsonb; anchor text;
  seal_count integer; seal_required integer; connected_count integer; hold_count integer;
begin
  select * into c from public.crew_access where token_hash=encode(extensions.digest(p_token,'sha256'),'hex');
  if c.crew_id is null then raise exception 'unauthorized'; end if;
  perform pani_private.containment_tick('W77-01');
  select * into s from pani_private.containment_session where session_id='W77-01' for update;
  if not exists(select 1 from pani_private.containment_participant p where p.session_id='W77-01' and p.crew_id=c.crew_id and p.joined) then
    raise exception 'not_joined';
  end if;
  update pani_private.containment_participant set last_seen=now() where session_id='W77-01' and crew_id=c.crew_id;
  st:=s.state; sec:=s.secret_state; ev:=coalesce(st->'event','{}'::jsonb);
  active_event:=st->>'active_event'; phase:=ev->>'vote_phase'; rep:=st->>'representative_id'; witness:=st->>'witness_id';

  if p_action='vote' then
    value:=left(trim(coalesce(p_payload->>'value','')),40);
    if active_event is null or phase is null or value='' then raise exception 'vote_unavailable'; end if;
    if active_event='knowledge' then raise exception 'direct_play_required'; end if;
    if active_event='energy' and value not in ('advance','stable','volatile') then raise exception 'invalid_vote'; end if;
    if active_event='blood' and (ev->>'phase'<>'beats' or value not in ('A','B','C')) then raise exception 'invalid_vote'; end if;
    if active_event='death' and (ev->>'phase'<>'cycles' or value not in ('clock','lamp','door','sample','chair','mirror')) then raise exception 'invalid_vote'; end if;
    insert into pani_private.containment_vote(session_id,event_id,phase_key,crew_id,value,updated_at)
    values ('W77-01',active_event,phase,c.crew_id,value,now())
    on conflict (session_id,event_id,phase_key,crew_id) do update set value=excluded.value,updated_at=now();
    perform pani_private.containment_log_event('W77-01',c.display_name,'vote',active_event||':'||phase||':'||value);

  elsif p_action='knowledge_mark' then
    if active_event<>'knowledge' or ev->>'phase' not in ('round1','round2') then raise exception 'knowledge_unavailable'; end if;
    select count(*) into connected_count from pani_private.containment_participant p
      where p.session_id='W77-01' and p.joined and p.last_seen>now()-interval '12 seconds';
    if connected_count>1 and coalesce(ev->>'last_actor_id','')=c.crew_id then raise exception 'alternate_operator_required'; end if;
    cell:=coalesce(p_payload->>'cell',''); size:=coalesce((ev->>'size')::int,3);
    if cell !~ '^c[0-9]{1,2}$' then raise exception 'invalid_cell'; end if;
    idx:=substring(cell from 2)::int;
    if idx<0 or idx>=size*size then raise exception 'invalid_cell'; end if;
    marks:=coalesce(ev->'marks','{}'::jsonb); if marks ? cell then raise exception 'occupied_cell'; end if;
    if coalesce(ev->'unstable','[]'::jsonb) @> jsonb_build_array(cell) then raise exception 'unstable_cell'; end if;
    rule_id:=sec#>>'{knowledge,rule_id}';
    if ev->>'phase'='round2' and rule_id='diagonal_prohibited' and idx/size=idx%size then raise exception 'rule_violation'; end if;
    if ev->>'phase'='round2' and rule_id='false_center' and idx in (5,6,9,10) then raise exception 'rule_violation'; end if;
    mark:=coalesce(ev->>'current_mark','X'); marks:=jsonb_set(marks,array[cell],to_jsonb(mark),true);
    ev:=ev||jsonb_build_object('marks',marks,'current_mark',case when mark='X' then 'O' else 'X' end,
      'move',coalesce((ev->>'move')::int,0)+1,'last_actor_id',c.crew_id);
    if pani_private.containment_knowledge_line(marks,size,mark) then
      wins:=coalesce((ev->>'wins')::int,0)+1;
      if ev->>'phase'='round1' then
        ev:=jsonb_build_object('phase','round2','round',2,'size',4,'marks','{}'::jsonb,'current_mark','X','move',0,
          'wins',wins,'unstable',case when rule_id='mobile_cell' then jsonb_build_array('c7') else '[]'::jsonb end,
          'absent','[]'::jsonb,'rule_title','REGRA VARIÁVEL','rule_text',case rule_id
            when 'diagonal_prohibited' then 'Marcas na diagonal principal são rejeitadas.'
            when 'false_center' then 'O centro geométrico é uma zona falsa.'
            when 'mobile_cell' then 'Uma casa móvel permanece instável nesta rodada.'
            else 'Uma linha de três encerra a rodada antes da quarta marca.' end,
          'hint',null,'locked',false,'last_actor_id',null,'vote_phase','knowledge:r2:m1');
      else
        ev:=jsonb_build_object('phase','missing','round',3,'size',3,'marks',jsonb_build_object('c1','X','c7','X'),
          'current_mark','X','move',0,'wins',wins,'unstable','[]'::jsonb,'absent',jsonb_build_array('c4'),
          'rule_title','CASA AUSENTE','rule_text','A casa removida continua pertencendo ao tabuleiro.',
          'hint','A ausência também ocupa uma posição.','locked',false,'last_actor_id',null,'vote_phase','knowledge:missing');
      end if;
    elsif (select count(*) from jsonb_object_keys(marks))>=size*size-jsonb_array_length(coalesce(ev->'unstable','[]'::jsonb)) then
      ev:=ev||jsonb_build_object('marks','{}'::jsonb,'current_mark','X','move',0,'last_actor_id',null);
      st:=jsonb_set(st,'{saturation}',to_jsonb(least(8,coalesce((st->>'saturation')::int,0)+1)));
    else
      ev:=ev||jsonb_build_object('vote_phase','knowledge:r'||coalesce(ev->>'round','1')||':m'||(coalesce((ev->>'move')::int,0)+1));
    end if;
    st:=jsonb_set(st,'{event}',ev,true);

  elsif p_action='knowledge_missing' then
    if active_event<>'knowledge' or ev->>'phase'<>'missing' or p_payload->>'cell'<>'c4' then raise exception 'missing_house_required'; end if;
    st:=pani_private.containment_capture(st,'knowledge');
    delete from pani_private.containment_vote v where v.session_id='W77-01' and v.event_id='knowledge';

  elsif p_action in ('knowledge_scan','knowledge_lock') then
    if active_event<>'knowledge' then raise exception 'knowledge_unavailable'; end if;
    if p_action='knowledge_scan' then
      if coalesce((st#>>'{pani_charges,scan}')::int,0)<1 then raise exception 'charge_unavailable'; end if;
      st:=jsonb_set(st,'{pani_charges,scan}','0'::jsonb,true);
      ev:=ev||jsonb_build_object('hint',case sec#>>'{knowledge,rule_id}'
        when 'diagonal_prohibited' then 'SCAN: a diagonal principal não aceita matéria simbólica.'
        when 'false_center' then 'SCAN: o centro exibido não pertence ao tabuleiro lógico.'
        when 'mobile_cell' then 'SCAN: a casa C7 está deslocada da malha.'
        else 'SCAN: conclua a linha antes que uma quarta marca a invalide.' end);
    else
      if coalesce((st#>>'{pani_charges,lock}')::int,0)<1 then raise exception 'charge_unavailable'; end if;
      st:=jsonb_set(st,'{pani_charges,lock}','0'::jsonb,true); ev:=ev||jsonb_build_object('locked',true);
    end if;
    st:=jsonb_set(st,'{event}',ev,true);

  elsif p_action='energy_move' then
    if active_event<>'energy' or c.crew_id<>rep then raise exception 'representative_required'; end if;
    pos:=coalesce((ev->>'position')::int,0); pulse:=greatest(1,least(6,coalesce((ev->>'pulse')::int,1)));
    overload:=coalesce((ev->>'overload')::int,0); choice:=coalesce(p_payload->>'route','stable');
