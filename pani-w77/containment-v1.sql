language plpgsql
security definer
set search_path = ''
as $$
declare s pani_private.containment_session%rowtype; st jsonb; sec jsonb; ev jsonb;
  active_event text; target text; code text; rep text; witness text; kind text; rule_id text;
  duration integer; statuses jsonb; case_data jsonb; deck jsonb; delta integer; value integer;
