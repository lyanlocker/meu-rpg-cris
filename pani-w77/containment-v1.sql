-- ADUNATIO // PROTOCOLO PANI // EVENTOS DE CONTENCAO ANOMALA v1.1
-- Estado sincronizado, votos, reconexao e corrupcao secreta do Mestre.

create schema if not exists pani_private;
revoke all on schema pani_private from public, anon, authenticated;

create table if not exists pani_private.containment_session (
  session_id text primary key,
  join_code text,
  state jsonb not null default '{}'::jsonb,
  secret_state jsonb not null default '{}'::jsonb,
  revision bigint not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists pani_private.containment_participant (
  session_id text not null references pani_private.containment_session(session_id) on delete cascade,
  crew_id text not null references public.crew_access(crew_id) on delete cascade,
  joined boolean not null default true,
  joined_at timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  hold_until timestamptz,
  primary key (session_id, crew_id)
);

create table if not exists pani_private.containment_vote (
  session_id text not null references pani_private.containment_session(session_id) on delete cascade,
  event_id text not null,
  phase_key text not null,
  crew_id text not null references public.crew_access(crew_id) on delete cascade,
  value text not null check (char_length(value) between 1 and 40),
  updated_at timestamptz not null default now(),
  primary key (session_id, event_id, phase_key, crew_id)
);

create table if not exists pani_private.containment_log (
  id bigint generated by default as identity primary key,
  session_id text not null,
  actor text not null,
  event_type text not null,
  detail text,
  created_at timestamptz not null default now()
);

create index if not exists containment_participant_presence_idx
  on pani_private.containment_participant(session_id, joined, last_seen desc);
create index if not exists containment_participant_crew_idx
  on pani_private.containment_participant(crew_id);
create index if not exists containment_vote_phase_idx
  on pani_private.containment_vote(session_id, event_id, phase_key, updated_at desc);
create index if not exists containment_vote_crew_idx
  on pani_private.containment_vote(crew_id);
create index if not exists containment_log_session_idx
  on pani_private.containment_log(session_id, created_at desc);

alter table pani_private.containment_session enable row level security;
alter table pani_private.containment_participant enable row level security;
alter table pani_private.containment_vote enable row level security;
alter table pani_private.containment_log enable row level security;
revoke all on all tables in schema pani_private from public, anon, authenticated;
revoke all on all sequences in schema pani_private from public, anon, authenticated;

