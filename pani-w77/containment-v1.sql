create or replace function pani_private.containment_vote_summary(
  p_session text, p_event text, p_phase text)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select coalesce(jsonb_object_agg(q.value, q.total), '{}'::jsonb)
  from (
    select v.value, count(*)::int as total
    from pani_private.containment_vote v
    where v.session_id = p_session and v.event_id = p_event and v.phase_key = p_phase
    group by v.value order by v.value
  ) q;
$$;

create or replace function pani_private.containment_knowledge_line(
  p_marks jsonb, p_size integer, p_mark text)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare r integer; c integer; needed integer := 3;
begin
  if p_size not between 3 and 4 or p_mark not in ('X','O') then return false; end if;
  for r in 0..p_size-1 loop
    for c in 0..p_size-needed loop
      if p_marks->>('c'||(r*p_size+c)) = p_mark
         and p_marks->>('c'||(r*p_size+c+1)) = p_mark
         and p_marks->>('c'||(r*p_size+c+2)) = p_mark then return true; end if;
    end loop;
  end loop;
  for c in 0..p_size-1 loop
    for r in 0..p_size-needed loop
      if p_marks->>('c'||(r*p_size+c)) = p_mark
         and p_marks->>('c'||((r+1)*p_size+c)) = p_mark
         and p_marks->>('c'||((r+2)*p_size+c)) = p_mark then return true; end if;
    end loop;
  end loop;
  for r in 0..p_size-needed loop
    for c in 0..p_size-needed loop
      if p_marks->>('c'||(r*p_size+c)) = p_mark
         and p_marks->>('c'||((r+1)*p_size+c+1)) = p_mark
         and p_marks->>('c'||((r+2)*p_size+c+2)) = p_mark then return true; end if;
    end loop;
    for c in 2..p_size-1 loop
      if p_marks->>('c'||(r*p_size+c)) = p_mark
         and p_marks->>('c'||((r+1)*p_size+c-1)) = p_mark
         and p_marks->>('c'||((r+2)*p_size+c-2)) = p_mark then return true; end if;
    end loop;
  end loop;
  return false;
end;
$$;

create or replace function pani_private.containment_blood_case(p_beat integer)
