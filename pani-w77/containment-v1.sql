    select least(4,greatest(1,count(*) filter (where p.crew_id<>rep)))::int into seal_required
      from pani_private.containment_participant p
      where p.session_id='W77-01' and p.joined and p.last_seen>now()-interval '12 seconds';
    select count(distinct v.value) into seal_count from pani_private.containment_vote v
      where v.session_id='W77-01' and v.event_id='blood' and v.phase_key='blood:seals';
    if seal_count>=seal_required and coalesce((ev->>'representative_ready')::boolean,false) then st:=pani_private.containment_capture(st,'blood'); end if;

  elsif p_action='death_confirm' then
