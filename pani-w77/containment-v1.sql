        ev:=ev||jsonb_build_object('cycle',cycle,'scene_kind',scene#>>'{public,scene_kind}',
          'changed_visuals',scene#>'{public,changed_visuals}','missing_object',null,'memory_overlay',false,
          'attempts',0,'vote_phase','death:c'||cycle);
        sec:=jsonb_set(sec,'{death}',jsonb_build_object('cycle',cycle,'answer',scene->>'answer'),true);
        st:=st||jsonb_build_object('event',ev,'witness_id',null);
      end if;
    else
      ev:=ev||jsonb_build_object('attempts',coalesce((ev->>'attempts')::int,0)+1);
      st:=jsonb_set(st,'{event}',ev,true);st:=jsonb_set(st,'{saturation}',to_jsonb(least(8,coalesce((st->>'saturation')::int,0)+1)));
    end if;

  elsif p_action='death_anchor' then
    if active_event<>'death' or c.crew_id<>witness or ev->>'anchor' is not null then raise exception 'anchor_unavailable'; end if;
    value:=coalesce(p_payload->>'object',''); if value not in ('clock','lamp','door','sample','chair','mirror') then raise exception 'invalid_object'; end if;
    ev:=ev||jsonb_build_object('anchor',value);st:=jsonb_set(st,'{event}',ev,true);

  elsif p_action='death_hold' then
    if active_event<>'death' or ev->>'phase'<>'final' then raise exception 'final_unavailable'; end if;
    update pani_private.containment_participant set hold_until=now()+interval '2500 milliseconds',last_seen=now()
      where session_id='W77-01' and crew_id=c.crew_id;
    select count(*) into connected_count from pani_private.containment_participant p
      where p.session_id='W77-01' and p.joined and p.last_seen>now()-interval '12 seconds';
    select count(*) into hold_count from pani_private.containment_participant p
      where p.session_id='W77-01' and p.joined and p.last_seen>now()-interval '12 seconds' and p.hold_until>now();
    if connected_count>=1 and hold_count>=connected_count then st:=pani_private.containment_capture(st,'death'); end if;
  else
    raise exception 'unknown_action';
  end if;

  update pani_private.containment_session set state=st,secret_state=sec,revision=revision+1,updated_at=now() where session_id='W77-01';
  perform pani_private.containment_log_event('W77-01',c.display_name,p_action,active_event);
  return public.pani_containment_crew_state(p_token);
end;
$$;

create or replace function public.pani_containment_master_state(p_pin text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare s pani_private.containment_session%rowtype; players jsonb; votes jsonb; logs jsonb;
begin
  if not public.pani_master_valid(p_pin) then raise exception 'unauthorized'; end if;
  perform pani_private.containment_tick('W77-01');
  select * into s from pani_private.containment_session where session_id='W77-01';
  select coalesce(jsonb_agg(jsonb_build_object('crew_id',ca.crew_id,'display_name',ca.display_name,'module',ca.module,
    'joined',coalesce(p.joined,false),'connected',coalesce(p.last_seen>now()-interval '12 seconds',false),'last_seen',p.last_seen)
    order by ca.display_name),'[]'::jsonb) into players
  from public.crew_access ca left join pani_private.containment_participant p on p.crew_id=ca.crew_id and p.session_id='W77-01';
  select coalesce(jsonb_agg(jsonb_build_object('event_id',v.event_id,'phase_key',v.phase_key,'crew_id',v.crew_id,
    'display_name',ca.display_name,'value',v.value,'updated_at',v.updated_at) order by v.updated_at),'[]'::jsonb) into votes
  from pani_private.containment_vote v join public.crew_access ca on ca.crew_id=v.crew_id where v.session_id='W77-01';
  select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb) into logs
  from (select id,actor,event_type,detail,created_at from pani_private.containment_log where session_id='W77-01' order by created_at desc limit 80) x;
  return jsonb_build_object('session_id','W77-01','join_code',s.join_code,'state',s.state,'secret_state',s.secret_state,
    'revision',s.revision,'server_time',now(),'players',players,'votes',votes,'logs',logs);
end;
$$;

create or replace function public.pani_containment_master_action(
  p_pin text, p_action text, p_payload jsonb default '{}'::jsonb)
