    sec:=sec||jsonb_build_object('corruption',jsonb_build_object('event',active_event,'kind',kind),'corruption_backup',backup);
    if active_event='knowledge' then
      if kind='semantic_swap' then ev:=ev||jsonb_build_object('rule_text','A casa instável é obrigatória para validar a linha.');
      else ghost:='c'||floor(random()*greatest(1,coalesce((ev->>'size')::int,3)^2))::int;ev:=ev||jsonb_build_object('ghost_cells',coalesce(ev->'ghost_cells','[]'::jsonb)||jsonb_build_array(ghost)); end if;
    elsif active_event='energy' then
      if kind='charged_pulse' then ev:=ev||jsonb_build_object('pulse',least(6,coalesce((ev->>'pulse')::int,1)+2));
      else sec:=jsonb_set(sec,'{energy,override_card}',to_jsonb('ANFITRIÃO'::text),true);ev:=ev||jsonb_build_object('card_label_override','PULSO VAZIO'); end if;
    elsif active_event='blood' then
      if kind='corrupted_vote' then sec:=jsonb_set(sec,'{blood,fake_votes}',jsonb_build_object('A',67,'B',17,'C',16),true);
      else ev:=jsonb_set(ev,'{readings,0}',to_jsonb('A apresenta todos os parâmetros estáveis.'::text),true)||jsonb_build_object('one_may_lie',true); end if;
    else
      if kind='missing_frame' then ev:=ev||jsonb_build_object('missing_object','chair','missing_until',(now()+interval '2 seconds')::text);
      elsif kind='memory_overlay' then ev:=ev||jsonb_build_object('memory_overlay',true);
      else ev:=ev||jsonb_build_object('changed_visuals',coalesce(ev->'changed_visuals','[]'::jsonb)||jsonb_build_array('lamp')); end if;
    end if;
    st:=st||jsonb_build_object('event',ev,'corruption_charges',coalesce((st->>'corruption_charges')::int,0)-1,
      'glitch',jsonb_build_object('revision',coalesce((st#>>'{glitch,revision}')::int,0)+1,'duration_ms',duration,'at',now()),
      'announcement','INTERFERÊNCIA DETECTADA','announcement_revision',coalesce((st->>'announcement_revision')::int,0)+1);

  elsif p_action='restore_corruption' then
    backup:=sec->'corruption_backup'; if backup is null or backup='null'::jsonb then raise exception 'no_corruption'; end if;
    if backup ? 'event' then
      st:=jsonb_set(st,'{event}',backup->'event',true);
      sec:=jsonb_set(sec,array[active_event],coalesce(backup->'event_secret','{}'::jsonb),true);
    else
      st:=jsonb_set(st,'{event}',backup,true);
    end if;
    st:=jsonb_set(st,'{corruption_charges}',to_jsonb(least(2,coalesce((st->>'corruption_charges')::int,0)+1)),true);
    sec:=jsonb_set(sec,'{blood,fake_votes}','null'::jsonb,true)||jsonb_build_object('corruption',null,'corruption_backup',null);

  elsif p_action='pause' then
    if coalesce((st->>'paused')::boolean,false) then
      st:=st||jsonb_build_object('paused',false,'timer_end',case when st->>'timer_remaining' is null then null else (now()+make_interval(secs=>(st->>'timer_remaining')::int))::text end,'timer_remaining',null);
    else
      st:=st||jsonb_build_object('paused',true,'timer_remaining',case when st->>'timer_end' is null then null else greatest(0,extract(epoch from ((st->>'timer_end')::timestamptz-now()))::int) end,'timer_end',null);
    end if;

  elsif p_action='saturation' then
    if p_payload ? 'value' then value:=greatest(0,least(8,(p_payload->>'value')::int));
    else delta:=greatest(-8,least(8,coalesce((p_payload->>'delta')::int,0)));value:=greatest(0,least(8,coalesce((st->>'saturation')::int,0)+delta));end if;
    st:=jsonb_set(st,'{saturation}',to_jsonb(value),true);

  elsif p_action='grant_hint' then
    ev:=ev||jsonb_build_object('hint',left(coalesce(p_payload->>'text','PANI detecta uma inconsistência local.'),500));st:=jsonb_set(st,'{event}',ev,true);

  elsif p_action='force_phase' then
    ev:=ev||jsonb_build_object('phase',left(coalesce(p_payload->>'phase',ev->>'phase'),40));st:=jsonb_set(st,'{event}',ev,true);

  elsif p_action='clear_votes' then
    if active_event is null then
      delete from pani_private.containment_vote v where v.session_id='W77-01';
    else
      delete from pani_private.containment_vote v where v.session_id='W77-01' and v.event_id=active_event;
    end if;

  elsif p_action='knowledge_rule' then
    if active_event<>'knowledge' then raise exception 'knowledge_only'; end if;
    rule_id:=coalesce(p_payload->>'rule_id','anti_three');sec:=jsonb_set(sec,'{knowledge,rule_id}',to_jsonb(rule_id),true);
    ev:=ev||jsonb_build_object('rule_text',case rule_id when 'diagonal_prohibited' then 'Marcas na diagonal principal são rejeitadas.' when 'false_center' then 'O centro geométrico é uma zona falsa.' when 'mobile_cell' then 'Uma casa móvel permanece instável nesta rodada.' else 'Uma linha de três encerra a rodada antes da quarta marca.' end);st:=jsonb_set(st,'{event}',ev,true);

  elsif p_action='energy_pulse' then
    if active_event<>'energy' then raise exception 'energy_only'; end if; value:=greatest(1,least(6,(p_payload->>'value')::int));ev:=ev||jsonb_build_object('pulse',value);st:=jsonb_set(st,'{event}',ev,true);

  elsif p_action='energy_card' then
    if active_event<>'energy' then raise exception 'energy_only'; end if;sec:=jsonb_set(sec,'{energy,override_card}',to_jsonb(upper(left(p_payload->>'card',80))),true);

  elsif p_action='death_scene' then
    if active_event<>'death' then raise exception 'death_only'; end if;value:=greatest(1,least(4,(p_payload->>'cycle')::int));case_data:=pani_private.containment_death_case(value,ev->>'anchor');
    ev:=ev||jsonb_build_object('phase','cycles','cycle',value,'scene_kind',case_data#>>'{public,scene_kind}','changed_visuals',case_data#>'{public,changed_visuals}','vote_phase','death:c'||value);
    sec:=jsonb_set(sec,'{death}',jsonb_build_object('cycle',value,'answer',case_data->>'answer'),true);st:=jsonb_set(st,'{event}',ev,true);

  elsif p_action='blood_timer' then
    if active_event<>'blood' then raise exception 'blood_only'; end if;timer_seconds:=greatest(12,least(18,(p_payload->>'seconds')::int));ev:=ev||jsonb_build_object('beat_seconds',timer_seconds);st:=st||jsonb_build_object('event',ev,'timer_end',(now()+make_interval(secs=>timer_seconds))::text);

  elsif p_action='remove_player' then
    target:=coalesce(p_payload->>'crew_id','');update pani_private.containment_participant set joined=false,hold_until=null where session_id='W77-01' and crew_id=target;
    if st->>'representative_id'=target then st:=jsonb_set(st,'{representative_id}','null'::jsonb,true);end if;
    if st->>'witness_id'=target then st:=jsonb_set(st,'{witness_id}','null'::jsonb,true);end if;

  elsif p_action='reconnect_player' then
    target:=coalesce(p_payload->>'crew_id','');
    insert into pani_private.containment_participant(session_id,crew_id,joined,last_seen) values ('W77-01',target,true,now())
    on conflict(session_id,crew_id) do update set joined=true,last_seen=now();

  elsif p_action='contain_event' then
    if active_event is null then raise exception 'no_active_event'; end if;st:=pani_private.containment_capture(st,active_event);delete from pani_private.containment_vote v where v.session_id='W77-01' and v.event_id=active_event;

  elsif p_action='end_event' then
    if active_event is null then raise exception 'no_active_event'; end if;statuses:=jsonb_set(st->'event_status',array[active_event],'"available"'::jsonb,true);
    st:=st||jsonb_build_object('status','lobby','active_event',null,'event_status',statuses,'representative_id',null,'witness_id',null,'event','{}'::jsonb,'timer_end',null,'paused',false);

  elsif p_action='pani_say' then
    st:=st||jsonb_build_object('announcement',left(coalesce(p_payload->>'text','PANI aguarda instruções.'),600),'announcement_revision',coalesce((st->>'announcement_revision')::int,0)+1);

  elsif p_action='residue_reveal' then
    if st->>'residue_status'<>'available' then raise exception 'residue_unavailable'; end if;
    st:=st||jsonb_build_object('residue_status','revealed','announcement','RESÍDUO BIOLÓGICO NÃO CATALOGADO // SETOR AMBIENTAL','announcement_revision',coalesce((st->>'announcement_revision')::int,0)+1);

  elsif p_action='residue_complete' then
    if st->>'residue_status'<>'revealed' then raise exception 'residue_unavailable'; end if;
    st:=st||jsonb_build_object('residue_status','correlated','announcement','CORRELAÇÃO AMBIENTAL PRESERVADA. PRÓXIMA FASE SOB CONTROLE DO DIRETOR.','announcement_revision',coalesce((st->>'announcement_revision')::int,0)+1);
  else
    raise exception 'unknown_action';
  end if;

  update pani_private.containment_session set state=st,secret_state=sec,revision=revision+1,updated_at=now() where session_id='W77-01';
  perform pani_private.containment_log_event('W77-01','MASTER',p_action,coalesce(target,active_event));
  return public.pani_containment_master_state(p_pin);
end;
