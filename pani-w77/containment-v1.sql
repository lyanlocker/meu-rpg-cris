  elsif p_action='close_session' then
    st:=pani_private.containment_default_state();sec:=pani_private.containment_default_secret();
    delete from pani_private.containment_vote where session_id='W77-01';
    delete from pani_private.containment_participant where session_id='W77-01';
    update pani_private.containment_session set join_code=null,state=st,secret_state=sec,revision=revision+1,updated_at=now() where session_id='W77-01';
    perform pani_private.containment_log_event('W77-01','MASTER','session_closed',null);
    return public.pani_containment_master_state(p_pin);
  end if;

  if not coalesce((st->>'released')::boolean,false) then raise exception 'session_closed'; end if;

  if p_action='set_available' then
    target:=coalesce(p_payload->>'event',''); if target not in ('knowledge','energy','blood','death') then raise exception 'invalid_event'; end if;
    statuses:=coalesce(st->'event_status','{}'::jsonb);
    if statuses->>target='contained' then raise exception 'event_contained'; end if;
