create or replace function pani_private.containment_death_case(p_cycle integer, p_anchor text default null)
returns jsonb
language plpgsql
immutable
set search_path = ''
as $$
declare answer text; fallback text; kind text;
begin
  case greatest(1, least(4, p_cycle))
    when 1 then answer := 'clock'; fallback := 'lamp'; kind := 'obvious';
    when 2 then answer := 'sample'; fallback := 'chair'; kind := 'two_suspects';
    when 3 then answer := 'door'; fallback := 'mirror'; kind := 'order';
    else answer := 'mirror'; fallback := 'lamp'; kind := 'temporal';
  end case;
  if answer = p_anchor then answer := fallback; end if;
  return jsonb_build_object(
    'answer', answer,
    'public', jsonb_build_object(
      'scene_kind', kind,
      'changed_visuals', jsonb_build_array(answer),
      'missing_object', null,
      'memory_overlay', false
    )
  );
end;
$$;

create or replace function pani_private.containment_capture(p_state jsonb, p_event text)
returns jsonb
language plpgsql
immutable
set search_path = ''
as $$
declare st jsonb := p_state; mods jsonb; statuses jsonb; n integer; sat integer;
begin
  mods := coalesce(st->'modules_restored','[]'::jsonb);
  if not mods @> jsonb_build_array(p_event) then mods := mods || jsonb_build_array(p_event); end if;
  statuses := jsonb_set(coalesce(st->'event_status','{}'::jsonb), array[p_event], '"contained"'::jsonb, true);
  n := jsonb_array_length(mods);
  sat := greatest(0, coalesce((st->>'saturation')::int,0)-1);
  st := st || jsonb_build_object(
    'modules_restored', mods,
    'event_status', statuses,
    'active_event', null,
    'status', case when n = 4 then 'contained' else 'lobby' end,
    'representative_id', null,
    'witness_id', null,
    'paused', false,
    'timer_end', null,
    'timer_remaining', null,
    'saturation', sat,
    'event', '{}'::jsonb,
    'residue_status', case when n = 4 then 'available' else coalesce(st->>'residue_status','locked') end,
    'announcement', case when n = 4
      then 'QUATRO ASSINATURAS RECAPTURADAS. VARREDURA LIMPA DISPONÍVEL.'
      else 'ASSINATURA RECAPTURADA. MÓDULO PANI RESTAURADO.' end,
    'announcement_revision', coalesce((st->>'announcement_revision')::int,0)+1
  );
  return st;
end;
$$;

create or replace function pani_private.containment_tick(p_session text)
returns void
language plpgsql
volatile
set search_path = ''
as $$
declare s pani_private.containment_session%rowtype; st jsonb; sec jsonb; ev jsonb;
  beat integer; stab integer; hemo integer; picked text; answer text; nxt jsonb;
begin
  select * into s from pani_private.containment_session where session_id=p_session for update;
  if s.session_id is null then return; end if;
  st := s.state; sec := s.secret_state;
  if st->>'active_event' <> 'blood' or coalesce((st->>'paused')::boolean,false)
     or st->>'timer_end' is null or (st->>'timer_end')::timestamptz > now()
     or st#>>'{event,phase}' <> 'beats' then return; end if;

  ev := st->'event'; beat := coalesce((ev->>'beat')::int,1);
  stab := coalesce((ev->>'stabilization')::int,0); hemo := coalesce((ev->>'hemorrhage')::int,0);
  picked := ev->>'selected_valve'; answer := sec#>>'{blood,answer}';
  if picked = answer then stab := stab + 1; else hemo := hemo + 1; end if;
  if hemo >= 3 then
    stab := 2; hemo := 0;
    st := jsonb_set(st,'{saturation}',to_jsonb(least(8,coalesce((st->>'saturation')::int,0)+1)));
    st := st || jsonb_build_object('announcement','HEMORRAGIA CRÍTICA. RETORNO AO PATAMAR 2/4.','announcement_revision',coalesce((st->>'announcement_revision')::int,0)+1);
  end if;
  if stab >= 4 then
    ev := ev || jsonb_build_object('phase','final','stabilization',4,'hemorrhage',hemo,'selected_valve',null,'representative_ready',false,'vote_phase','blood:seals');
    st := st || jsonb_build_object('event',ev,'timer_end',null,'timer_remaining',null);
  else
    beat := beat + 1; nxt := pani_private.containment_blood_case(beat);
    ev := ev || jsonb_build_object('beat',beat,'stabilization',stab,'hemorrhage',hemo,
      'readings',nxt->'readings','selected_valve',null,'vote_phase','blood:beat'||beat,
      'one_may_lie',false);
    sec := jsonb_set(sec,'{blood}',jsonb_build_object('beat_index',beat,'answer',nxt->>'answer','fake_votes',null),true);
    st := st || jsonb_build_object('event',ev,'timer_end',(now()+make_interval(secs=>coalesce((ev->>'beat_seconds')::int,15)))::text);
  end if;
  update pani_private.containment_session set state=st,secret_state=sec,revision=revision+1,updated_at=now() where session_id=p_session;
  perform pani_private.containment_log_event(p_session,'PANI','blood_beat_resolved','beat='||beat||';picked='||coalesce(picked,'none'));
end;
$$;

