    delete from pani_private.containment_participant where session_id='W77-01';
    update pani_private.containment_session set join_code=code,state=st,secret_state=sec,revision=revision+1,updated_at=now() where session_id='W77-01';
    perform pani_private.containment_log_event('W77-01','MASTER','session_opened',code);
