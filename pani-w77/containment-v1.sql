      when 'ANÁRQUICO' then idx:=(array[-2,0,2,4])[1+floor(random()*4)::int];pos:=greatest(0,least(19,pos+idx));effect:='Dado anárquico: '||case when idx>=0 then '+' else '' end||idx||'.';
